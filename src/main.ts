import { createApp } from 'vue';
import App from './entrypoint/gui/App.vue';
import { createAppRouter } from './entrypoint/gui/router';
import { USE_CASES } from './entrypoint/gui/context';
import { useCases } from './bootstrap/container';
import { SESSION_STATE, createSessionState } from './entrypoint/gui/session-state';
import './entrypoint/gui/styles.css';
const router = createAppRouter(useCases);
const sessionState = createSessionState(useCases);
window.addEventListener('session-expired', () => { sessionState.refresh(); void router.replace({ path: '/login', query: { expired: '1' } }); });
window.addEventListener('storage', () => { sessionState.refresh(); if (!useCases.currentSession()) void router.replace('/login'); });
createApp(App).provide(USE_CASES, useCases).provide(SESSION_STATE, sessionState).use(router).mount('#app');
